#!/usr/bin/env python3
"""Convert a diagnostic session (events-*.json) into a Lua replay fixture.

Usage:
  python3 scripts/replay_session.py <session-dir> <output.lua>

The fixture preserves recorded event order. tests/replay_runner.lua
replays raw payloads through production RebornCompat logic and
compares normalized output against the recorded normalized result.
Only minimal, sanitized fixtures derived from a session belong in
the public repository; full sessions stay in the private
diagnostics repository.
"""
import glob
import hashlib
import json
import sys


def lua_value(v, depth=0):
    if v is None:
        return "nil"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{ " + ", ".join(lua_value(x, depth + 1) for x in v) + " }"
    if isinstance(v, dict):
        parts = []
        for k, val in v.items():
            key = k if k.isidentifier() else "[" + json.dumps(str(k)) + "]"
            parts.append(f"{key} = {lua_value(val, depth + 1)}")
        return "{ " + ", ".join(parts) + " }"
    return "nil"


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    session_dir, out_path = sys.argv[1], sys.argv[2]
    # Validate manifest completeness and hashes before conversion.
    manifest_path = session_dir + "/manifest.json"
    try:
        with open(manifest_path, encoding="utf-8") as fh:
            manifest = json.load(fh)
    except FileNotFoundError:
        print("error: manifest.json missing; session is incomplete")
        return 1
    for name, expected in sorted(manifest.get("files", {}).items()):
        try:
            with open(session_dir + "/" + name, "rb") as fh:
                digest = hashlib.sha256(fh.read()).hexdigest()
        except FileNotFoundError:
            print(f"error: manifest file missing: {name}")
            return 1
        if digest != expected:
            print(f"error: hash mismatch for {name}")
            return 1
    events = []
    for path in sorted(glob.glob(session_dir + "/events-*.json")):
        with open(path, encoding="utf-8") as fh:
            events.extend(json.load(fh))
    events.sort(key=lambda e: e.get("seq", 0))
    seqs = [e.get("seq") for e in events]
    if len(seqs) != len(set(seqs)):
        print("error: duplicated sequence numbers in session")
        return 1
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("-- Generated by scripts/replay_session.py; do not edit.\n")
        fh.write("return " + lua_value(events) + "\n")
    print(f"Wrote {len(events)} events to {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
